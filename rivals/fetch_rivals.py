"""Clone the rival repos listed in rivals.json into rivals/_src/ and write a launcher
rivals/<name>/bot.py for each, runnable by starter_kit/engine.py.

    python rivals/fetch_rivals.py            # fetch missing repos, (re)write launchers
    python rivals/fetch_rivals.py --update   # also re-pull existing clones

LOCAL SPARRING ONLY: never import rivals/ from bot/ (Rulebook 10.1).
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "_src"

LAUNCHER = '''"""Launcher for rival '{name}' ({repo}{at}:{dir}). Generated by fetch_rivals.py."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from mit_adapter import main
main(os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "_src", {clone!r}, *{parts!r}))
'''


def clone_name(repo, ref):
    return repo.replace("/", "__") + (f"@{ref}" if ref else "")


def main():
    update = "--update" in sys.argv
    rivals = {k: v for k, v in json.loads((HERE / "rivals.json").read_text()).items()
              if not k.startswith("_")}
    SRC.mkdir(exist_ok=True)
    done = set()
    for name, r in rivals.items():
        cname = clone_name(r["repo"], r["ref"])
        dest = SRC / cname
        if cname not in done:
            if not dest.exists():
                cmd = ["git", "clone", "-q", "--depth", "1"]
                if r["ref"]:
                    cmd += ["-b", r["ref"]]
                subprocess.run(cmd + [f"https://github.com/{r['repo']}.git", str(dest)], check=True)
                print(f"cloned  {r['repo']}{'@' + r['ref'] if r['ref'] else ''}")
            elif update:
                subprocess.run(["git", "-C", str(dest), "pull", "-q", "--ff-only"], check=True)
                print(f"updated {r['repo']}")
            done.add(cname)
        bot_dir = dest / r["dir"]
        if not (bot_dir / "player.py").exists():
            print(f"WARNING {name}: {bot_dir} has no player.py")
            continue
        out = HERE / name
        out.mkdir(exist_ok=True)
        (out / "bot.py").write_text(LAUNCHER.format(
            name=name, repo=r["repo"], at=f"@{r['ref']}" if r["ref"] else "", dir=r["dir"],
            clone=cname, parts=tuple(Path(r["dir"]).parts)))
        print(f"ready   rivals/{name}/bot.py  - {r['note']}")


if __name__ == "__main__":
    main()
